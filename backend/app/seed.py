"""Demo user and the clearly-labelled synthetic demo project.

Run ``python -m app.seed`` (or let startup do it when ``TRACEMIND_SEED_ON_STARTUP`` is on).
``python -m app.seed --reset`` deletes and regenerates the demo project with fresh timestamps.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import logging
import secrets
import uuid

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models import AnalysisRun, Incident, IngestionJob, Project, ProjectMember, User

log = logging.getLogger("tracemind.seed")
DEMO_EMAIL = "demo@tracemind.local"
DEMO_SLUG = "demo-shopflow"
DEMO_NAME = "ShopFlow · synthetic demo"


def ensure_demo_user(db: Session) -> User:
    from app.security import hash_password

    user = db.scalar(select(User).where(User.email == DEMO_EMAIL))
    if user is None:
        # Random password: the demo account is reachable only through /auth/demo.
        user = User(email=DEMO_EMAIL, display_name="Demo visitor", password_hash=hash_password(secrets.token_urlsafe(32)), is_demo=True)
        db.add(user)
        db.flush()
    project = db.scalar(select(Project).where(Project.slug == DEMO_SLUG))
    if project is not None and not db.scalar(select(ProjectMember).where(ProjectMember.project_id == project.id,
                                                                          ProjectMember.user_id == user.id)):
        db.add(ProjectMember(project_id=project.id, user_id=user.id, role="analyst"))
    db.commit()
    return user


def seed_demo(db: Session, reset: bool = False, analyze: bool = True) -> Project:
    from app.bench.generator import demo_scenario
    from app.ingestion.normalize import parse_file
    from app.services import jobs
    from app.services.analysis import create_run
    from app.services.detection import detect_project
    from app.services.ingestion import ingest_records
    from app.storage import get_storage, object_key

    project = db.scalar(select(Project).where(Project.slug == DEMO_SLUG))
    if project is not None and not reset:
        ensure_demo_user(db)
        return project
    if project is not None:
        db.delete(project)
        db.commit()

    user = ensure_demo_user(db)
    project = Project(id=uuid.uuid4(), name=DEMO_NAME, slug=DEMO_SLUG, is_demo=True, environments=["production"],
                      description="Synthetic e-commerce telemetry generated by TraceMind's fault generator. Two faults "
                                  "are injected: a bad payments-service deployment and inventory-db connection-pool "
                                  "exhaustion, plus a decoy deployment and a transient noise blip.",
                      analysis_settings={})
    project.members.append(ProjectMember(user_id=user.id, role="analyst"))
    db.add(project)
    db.commit()

    scenario = demo_scenario()
    content = "\n".join(json.dumps(r) for r in scenario.records).encode()
    job = IngestionJob(id=uuid.uuid4(), project_id=project.id, created_by=None, filename="shopflow-demo.jsonl",
                       file_format="jsonl", size_bytes=len(content), content_sha256=hashlib.sha256(content).hexdigest(),
                       environment="production", status="running", idempotency_key="demo-seed")
    job.storage_key = get_storage().put(object_key(str(project.id), str(job.id), job.filename), content)
    db.add(job)
    db.commit()
    result = parse_file(content, job.filename, {}, "production")
    job.total_rows, job.rejected_rows, job.duplicate_rows, job.errors = result.total_rows, result.rejected_rows, result.duplicate_rows, result.errors
    accepted, dupes = ingest_records(db, job, result.records)
    job.accepted_rows, job.duplicate_rows, job.processed_rows = accepted, job.duplicate_rows + dupes, job.total_rows
    job.detection_summary = detect_project(db, project.id, ["production"])
    job.status = "completed"
    db.commit()
    log.info("demo project seeded", extra={"events": accepted})

    if analyze:
        previous = jobs._inline
        jobs.set_inline(True)
        try:
            for incident in db.scalars(select(Incident).where(Incident.project_id == project.id)):
                if not db.scalar(select(AnalysisRun).where(AnalysisRun.incident_id == incident.id)):
                    create_run(db, incident, user)
        finally:
            jobs.set_inline(previous)
    return project


def main() -> None:
    from app.db import Base, SessionLocal, engine

    parser = argparse.ArgumentParser()
    parser.add_argument("--reset", action="store_true", help="delete and regenerate the demo project")
    parser.add_argument("--create-tables", action="store_true", help="create tables without Alembic (SQLite dev only)")
    args = parser.parse_args()
    if args.create_tables:
        Base.metadata.create_all(engine)
    with SessionLocal() as db:
        project = seed_demo(db, reset=args.reset)
        print(f"demo project ready: {project.name} ({project.id})")


if __name__ == "__main__":
    main()
